"""Generate runtime/kernel_exports.h from nxdk's xboxkrnl.exe.def (CC0).

Usage: python tools/gen_kernel_exports.py third_party/nxdk/xboxkrnl.exe.def runtime/kernel_exports.h
"""
import re
import sys

LINE = re.compile(r"^\s+(@?)(\w+?)(?:@(\d+))?\s+@\s*(\d+)\s+NONAME(\s+DATA)?")


def parse(path):
    out = {}
    for line in open(path):
        m = LINE.match(line)
        if not m:
            continue
        fast, name, argbytes, ordinal, data = m.groups()
        conv = "K_DATA" if data else "K_FASTCALL" if fast else "K_STDCALL" if argbytes is not None else "K_CDECL"
        out[int(ordinal)] = (name, conv, int(argbytes or 0))
    return out


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    exports = parse(sys.argv[1])
    assert len(exports) > 360 and exports[156][0] == "KeTickCount", "unexpected def file contents"
    with open(sys.argv[2], "w") as h:
        h.write("/* Generated by tools/gen_kernel_exports.py from nxdk xboxkrnl.exe.def (CC0). */\n#pragma once\n\n")
        h.write("enum { K_NONE, K_STDCALL, K_FASTCALL, K_CDECL, K_DATA };\n")
        h.write("typedef struct { const char *name; unsigned char conv, argbytes; } KExport;\n\n")
        h.write(f"#define KERNEL_EXPORT_MAX {max(exports) + 1}\n")
        h.write("static const KExport g_kexports[KERNEL_EXPORT_MAX] = {\n")
        for o in sorted(exports):
            name, conv, n = exports[o]
            h.write(f'    [{o}] = {{"{name}", {conv}, {n}}},\n')
        h.write("};\n")
    print(f"wrote {len(exports)} exports")
